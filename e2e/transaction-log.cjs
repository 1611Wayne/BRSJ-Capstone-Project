// FT-8: document-review milestones, persistent history, and monthly reversions by Admin.
require('../tests/register-ts.cjs');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');
const {mockApplications}=require('../data/mockApplications.ts');
const {mockUsers}=require('../data/mockUsers.ts');
const {mockFeeSchedules}=require('../data/mockFeeSchedules.ts');
const {today}=require('../lib/workflow.ts');
const BASE=process.env.E2E_BASE||'http://localhost:3100',CHANNEL=process.env.E2E_CHANNEL??'msedge',KEY='san-jose-prototype-v2',ref='SJ-2026-000123';
const month=today().slice(0,7),[year,monthNumber]=month.split('-').map(Number);
const start=new Date(Date.UTC(year,monthNumber-1,1)-8*3600000).toISOString();
const nextStart=new Date(Date.UTC(year,monthNumber,1)-8*3600000).toISOString();
const nextMonth=new Date(Date.UTC(year,monthNumber,1)).toISOString().slice(0,7);
const audit=(id,userId,user,action,timestamp)=>({id,userId,user,action,timestamp,role:'admin',reference:'SJ-2026-000125',reversion:true,reason:'Monthly boundary fixture'});
const seed={users:mockUsers,applications:mockApplications.map(a=>a.reference===ref?{...a,documents:a.documents.map(d=>({...d,status:'Pending Review'}))}:a),schedules:mockFeeSchedules,audits:[audit('month-a',undefined,'Admin San Jose','Edit Fields',start),audit('month-b','admin-two','Second Admin','Void Transaction',start),audit('next-month','admin','Admin San Jose','Void Transaction',nextStart)],notifications:[],currentUserId:'staff-maria'};
let checks=0;const check=(name,ok)=>{assert.ok(ok,name);checks++;console.log('PASS '+name)};
(async()=>{
 const browser=await chromium.launch({...(CHANNEL?{channel:CHANNEL}:{}),headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1280,height:1000}}),errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(([key,value])=>{if(!sessionStorage.getItem(key))sessionStorage.setItem(key,value)},[KEY,JSON.stringify(seed)]);
  const setUser=async id=>page.evaluate(([key,id])=>{const state=JSON.parse(sessionStorage.getItem(key));state.currentUserId=id;sessionStorage.setItem(key,JSON.stringify(state))},[KEY,id]);
  await page.goto(BASE+'/staff/assessment/'+ref);
  for(let i=0;i<3;i++)await page.getByRole('button',{name:'Mark Verified',exact:true}).first().click();
  const recorded=await page.evaluate(([key,ref])=>JSON.parse(sessionStorage.getItem(key)).applications.find(a=>a.reference===ref).documents,[KEY,ref]);
  check('document reviews store time and Staff identity',recorded.every(d=>d.reviewedAt&&d.reviewedBy==='Maria Staff'));
  await page.goto(BASE+'/staff/applications/'+ref);
  await page.getByRole('heading',{name:'Application Details',exact:true}).waitFor();
  const milestone=page.locator('tr').filter({has:page.getByRole('cell',{name:'Document Review Time',exact:true})});
  check('Service Processing shows the document review time including seconds',/\d{1,2}:\d{2}:\d{2}/.test(await milestone.innerText()));
  const log=page.getByRole('region',{name:'Full Transaction Log',exact:true});
  check('full log preserves all three review events',await log.locator('tbody tr').filter({hasText:'Requirements reviewed'}).count()===3);
  check('unreached verification stage has no invented time',(await page.locator('tr').filter({has:page.getByRole('cell',{name:'OR Verification Time',exact:true})}).innerText()).includes('—'));
  await page.reload();await log.waitFor();
  const reloaded=await page.evaluate(([key,ref])=>JSON.parse(sessionStorage.getItem(key)).applications.find(a=>a.reference===ref).documents,[KEY,ref]);
  check('review milestones and full history survive reload',JSON.stringify(recorded)===JSON.stringify(reloaded)&&await log.locator('tbody tr').filter({hasText:'Requirements reviewed'}).count()===3);

  await setUser('admin');await page.goto(BASE+'/admin/transaction-reversion');
  await page.locator('tbody tr').filter({hasText:ref}).getByRole('button',{name:'Revert',exact:true}).click();
  await page.getByLabel('Select Action').selectOption('Mark Under Review');
  await page.getByLabel('Reason for Reversion').fill('FT-8 timeline test');
  await page.getByRole('button',{name:'Confirm Reversion'}).click();
  await page.getByRole('dialog').waitFor({state:'detached'});
  await page.goto(BASE+'/admin/applications/'+ref);
  await log.waitFor();
  check('Admin timeline includes the reversion action and reason',(await log.innerText()).includes('Mark Under Review')&&(await log.innerText()).includes('FT-8 timeline test'));
  check('transaction timeline excludes other requests',!(await log.innerText()).includes('Monthly boundary fixture'));
  fs.mkdirSync(path.join(__dirname,'shots'),{recursive:true});
  await log.screenshot({path:path.join(__dirname,'shots','ft8-transaction-log.png')});
  await page.goto(BASE+'/admin/dashboard');
  const monthly=page.getByRole('region',{name:'Monthly Reversions by Admin',exact:true});await monthly.waitFor();
  await monthly.getByLabel('Reversion Month').fill(month);
  const adminCells=await monthly.locator('tbody tr').filter({hasText:'Admin San Jose'}).getByRole('cell').allTextContents();
  check('monthly table separates edits, voids, review actions, and total',JSON.stringify(adminCells)===JSON.stringify(['Admin San Jose','1','0','1','2']));
  const secondCells=await monthly.locator('tbody tr').filter({hasText:'Second Admin'}).getByRole('cell').allTextContents();
  check('reversions are counted separately per Admin',JSON.stringify(secondCells)===JSON.stringify(['Second Admin','0','1','0','1']));
  check('monthly total counts actions',(await monthly.innerText()).includes('Total reversion actions: 3'));
  await monthly.screenshot({path:path.join(__dirname,'shots','ft8-monthly-reversions.png')});
  await monthly.getByLabel('Reversion Month').fill(nextMonth);
  check('Manila midnight boundary places the next-month action correctly',await monthly.locator('tbody tr').count()===1&&(await monthly.innerText()).includes('Total reversion actions: 1'));
  await monthly.getByLabel('Reversion Month').fill('2020-01');
  check('months without reversions show an explicit empty state',(await monthly.innerText()).includes('No reversion actions recorded for this month.'));
  await setUser('resident-maria');await page.goto(BASE+'/resident/applications/'+ref);
  await page.getByRole('heading',{name:'Application Details',exact:true}).waitFor();
  check('internal transaction history is hidden from residents',await page.getByRole('region',{name:'Full Transaction Log',exact:true}).count()===0);
  await page.goto(BASE+'/resident/dashboard');await page.getByRole('heading',{name:/Welcome back/}).waitFor();
  check('monthly Admin reversions are hidden from residents',await page.getByRole('region',{name:'Monthly Reversions by Admin',exact:true}).count()===0);
  check('no browser errors',errors.length===0);
  console.log(`\n${checks}/${checks} checks passed`);
 }finally{await browser.close()}
})().catch(error=>{console.error('SCRIPT ERROR',error);process.exitCode=1});
